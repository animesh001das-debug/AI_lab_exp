filename = list(uploaded.keys())[0]

print("Uploaded file:", filename)


# ============================================================
# 2. READ DATASET
# ============================================================

df = pd.read_csv(io.BytesIO(uploaded[filename]))

print("\nDataset loaded successfully!")
print("Rows    :", df.shape[0])
print("Columns :", df.shape[1])

print("\nFirst 5 rows:")
display(df.head())


# ============================================================
# 3. DATASET INFORMATION
# ============================================================

print("\nColumn names:")
print(df.columns.tolist())

print("\nMissing values:")
print(df.isnull().sum())


# ============================================================
# 4. NUMERICAL FEATURES
# ============================================================

numeric_columns = df.select_dtypes(
    include=np.number
).columns.tolist()

print("\nNumerical features:")
for col in numeric_columns:
    print("-", col)


# ============================================================
# 5. FEATURE SELECTION
# ============================================================

print("\nSelect TWO features for 2D visualization.")

x_dropdown = widgets.Dropdown(
    options=numeric_columns,
    value="N" if "N" in numeric_columns else numeric_columns[0],
    description="X-axis:",
    layout=widgets.Layout(width="400px")
)

y_dropdown = widgets.Dropdown(
    options=numeric_columns,
    value="P" if "P" in numeric_columns else numeric_columns[1],
    description="Y-axis:",
    layout=widgets.Layout(width="400px")
)

display(x_dropdown)
display(y_dropdown)


# ============================================================
# 6. TARGET COLUMN
# ============================================================

target_dropdown = widgets.Dropdown(
    options=list(df.columns),
    value="label" if "label" in df.columns else df.columns[-1],
    description="Target:",
    layout=widgets.Layout(width="400px")
)

display(target_dropdown)


# ============================================================
# 7. K VALUE
# ============================================================

k_slider = widgets.IntSlider(
    value=5,
    min=1,
    max=15,
    step=1,
    description="K:",
    layout=widgets.Layout(width="400px")
)

display(k_slider)


# ============================================================
# 8. RUN BUTTON
# ============================================================

run_button = widgets.Button(
    description="Run KNN",
    button_style="success",
    layout=widgets.Layout(
        width="200px",
        height="40px"
    )
)

display(run_button)


# ============================================================
# 9. OUTPUT
# ============================================================

output = widgets.Output()

display(output)


# ============================================================
# 10. KNN FUNCTION
# ============================================================

def run_knn(button):

    with output:

        output.clear_output(wait=True)

        # ----------------------------------------------------
        # GET USER INPUT
        # ----------------------------------------------------

        x_feature = x_dropdown.value
        y_feature = y_dropdown.value
        target = target_dropdown.value
        K = k_slider.value

        print("=" * 60)
        print("             KNN CROP RECOMMENDATION")
        print("=" * 60)

        print("\nX-axis Feature :", x_feature)
        print("Y-axis Feature :", y_feature)
        print("Target         :", target)
        print("K              :", K)


        # ----------------------------------------------------
        # CHECK FEATURES
        # ----------------------------------------------------

        if x_feature == y_feature:

            print("\nERROR:")
            print("X-axis and Y-axis must be different.")

            return


        # ----------------------------------------------------
        # PREPARE DATA
        # ----------------------------------------------------

        data = df[
            [x_feature, y_feature, target]
        ].copy()

        data = data.dropna()


        # ----------------------------------------------------
        # X AND Y
        # ----------------------------------------------------

        X = data[
            [x_feature, y_feature]
        ]

        y = data[target]


        # ----------------------------------------------------
        # ENCODE TARGET
        # ----------------------------------------------------

        encoder = LabelEncoder()

        y_encoded = encoder.fit_transform(
            y.astype(str)
        )

        print("\nNumber of classes:",
              len(encoder.classes_))

        print("\nCrop classes:")

        for i, crop in enumerate(
            encoder.classes_
        ):
            print(i, "→", crop)


        # ----------------------------------------------------
        # TRAIN TEST SPLIT
        # ----------------------------------------------------

        X_train, X_test, y_train, y_test = train_test_split(
            X,
            y_encoded,
            test_size=0.20,
            random_state=42,
            stratify=y_encoded
        )


        # ----------------------------------------------------
        # FEATURE SCALING
        # ----------------------------------------------------

        scaler = StandardScaler()

        X_train_scaled = scaler.fit_transform(
            X_train
        )

        X_test_scaled = scaler.transform(
            X_test
        )


        # ----------------------------------------------------
        # KNN MODEL
        # ----------------------------------------------------

        if K > len(X_train_scaled):

            print("\nK is too large.")

            return

        model = KNeighborsClassifier(
            n_neighbors=K,
            metric="euclidean"
        )


        # ----------------------------------------------------
        # TRAIN
        # ----------------------------------------------------

        model.fit(
            X_train_scaled,
            y_train
        )


        # ----------------------------------------------------
        # PREDICTION
        # ----------------------------------------------------

        y_pred = model.predict(
            X_test_scaled
        )


        # ----------------------------------------------------
        # ACCURACY
        # ----------------------------------------------------

        accuracy = accuracy_score(
            y_test,
            y_pred
        )

        print("\n" + "=" * 60)
        print("                 RESULTS")
        print("=" * 60)

        print("\nTotal Samples    :", len(data))
        print("Training Samples :", len(X_train))
        print("Testing Samples  :", len(X_test))
        print("K                :", K)

        print(
            "\nAccuracy         :",
            f"{accuracy * 100:.2f}%"
        )


        # ====================================================
        # CONFUSION MATRIX
        # ====================================================

        print("\nConfusion Matrix:")

        cm = confusion_matrix(
            y_test,
            y_pred
        )

        print(cm)


        # ====================================================
        # CLASSIFICATION REPORT
        # ====================================================

        print("\nClassification Report:")

        print(
            classification_report(
                y_test,
                y_pred,
                target_names=encoder.classes_,
                zero_division=0
            )
        )


        # ====================================================
        # 2D VISUALIZATION
        # ====================================================

        print("\n" + "=" * 60)
        print("             STARTING 2D KNN ANIMATION")
        print("=" * 60)


        # ----------------------------------------------------
        # SELECT TEST POINT
        # ----------------------------------------------------

        test_point = X_test_scaled[0]

        actual_class = y_test[0]

        predicted_class = model.predict(
            test_point.reshape(1, -1)
        )[0]


        # ----------------------------------------------------
        # CALCULATE DISTANCES
        # ----------------------------------------------------

        distances = np.sqrt(
            np.sum(
                (X_train_scaled - test_point) ** 2,
                axis=1
            )
        )


        # ----------------------------------------------------
        # SORT DISTANCES
        # ----------------------------------------------------

        sorted_indices = np.argsort(
            distances
        )


        # ----------------------------------------------------
        # FIND K NEAREST NEIGHBOURS
        # ----------------------------------------------------

        nearest_indices = sorted_indices[:K]


        # ====================================================
        # CREATE GRAPH
        # ====================================================

        fig, ax = plt.subplots(
            figsize=(10, 7)
        )


        # ----------------------------------------------------
        # PLOT TRAINING DATA
        # ----------------------------------------------------

        classes = np.unique(
            y_train
        )

        for class_value in classes:

            points = X_train_scaled[
                y_train == class_value
            ]

            ax.scatter(
                points[:, 0],
                points[:, 1],
                s=60,
                label=str(
                    encoder.classes_[class_value]
                )
            )


        # ----------------------------------------------------
        # TEST POINT
        # ----------------------------------------------------

        ax.scatter(
            test_point[0],
            test_point[1],
            marker="*",
            s=350,
            edgecolors="black",
            linewidth=2,
            label="Test Point"
        )


        # ----------------------------------------------------
        # AXIS LABELS
        # ----------------------------------------------------

        ax.set_xlabel(
            x_feature + " (Scaled)",
            fontsize=12
        )

        ax.set_ylabel(
            y_feature + " (Scaled)",
            fontsize=12
        )

        ax.set_title(
            "KNN Crop Recommendation - 2D Visualization",
            fontsize=15
        )

        ax.grid(
            True,
            alpha=0.3
        )

        ax.legend(
            fontsize=7,
            bbox_to_anchor=(1.05, 1),
            loc="upper left"
        )


        # ----------------------------------------------------
        # INFORMATION BOX
        # ----------------------------------------------------

        info = ax.text(
            0.02,
            0.97,
            "",
            transform=ax.transAxes,
            verticalalignment="top",
            fontsize=10,
            bbox=dict(
                boxstyle="round",
                facecolor="white",
                alpha=0.9
            )
        )


        # ====================================================
        # ANIMATION
        # ====================================================

        lines = []


        def update(frame):

            # Remove old lines

            for line in lines:
                line.remove()

            lines.clear()


            # ------------------------------------------------
            # STEP 1
            # ------------------------------------------------

            if frame == 0:

                info.set_text(
                    "STEP 1\n\n"
                    "Test point selected\n"
                    "Finding nearest neighbours..."
                )


            # ------------------------------------------------
            # STEP 2
            # ------------------------------------------------

            elif 1 <= frame <= min(
                30,
                len(sorted_indices)
            ):

                index = sorted_indices[
                    frame - 1
                ]

                point = X_train_scaled[
                    index
                ]

                line, = ax.plot(
                    [
                        test_point[0],
                        point[0]
                    ],
                    [
                        test_point[1],
                        point[1]
                    ],
                    linestyle="--",
                    linewidth=1
                )

                lines.append(line)

                info.set_text(
                    "STEP 2: DISTANCE\n\n"
                    f"Training Point: {index + 1}\n"
                    f"Distance: {distances[index]:.3f}"
                )


            # ------------------------------------------------
            # STEP 3
            # ------------------------------------------------

            elif frame == min(
                30,
                len(sorted_indices)
            ) + 1:

                for index in nearest_indices:

                    point = X_train_scaled[
                        index
                    ]

                    line, = ax.plot(
                        [
                            test_point[0],
                            point[0]
                        ],
                        [
                            test_point[1],
                            point[1]
                        ],
                        linewidth=3
                    )

                    lines.append(line)


                neighbour_classes = y_train[
                    nearest_indices
                ]

                neighbour_names = [
                    encoder.classes_[c]
                    for c in neighbour_classes
                ]


                info.set_text(
                    "STEP 3: K NEAREST NEIGHBOURS\n\n"
                    f"K = {K}\n"
                    f"Neighbours = "
                    f"{neighbour_names}"
                )


            # ------------------------------------------------
            # STEP 4
            # ------------------------------------------------

            elif frame == min(
                30,
                len(sorted_indices)
            ) + 2:

                for index in nearest_indices:

                    point = X_train_scaled[
                        index
                    ]

                    line, = ax.plot(
                        [
                            test_point[0],
                            point[0]
                        ],
                        [
                            test_point[1],
                            point[1]
                        ],
                        linewidth=3
                    )

                    lines.append(line)


                neighbour_classes = y_train[
                    nearest_indices
                ]

                unique, counts = np.unique(
                    neighbour_classes,
                    return_counts=True
                )

                voting_text = ""

                for c, count in zip(
                    unique,
                    counts
                ):

                    voting_text += (
                        f"{encoder.classes_[c]}"
                        f" → {count} vote(s)\n"
                    )


                info.set_text(
                    "STEP 4: MAJORITY VOTING\n\n"
                    + voting_text
                )


            # ------------------------------------------------
            # STEP 5
            # ------------------------------------------------

            else:

                for index in nearest_indices:

                    point = X_train_scaled[
                        index
                    ]

                    line, = ax.plot(
                        [
                            test_point[0],
                            point[0]
                        ],
                        [
                            test_point[1],
                            point[1]
                        ],
                        linewidth=3
                    )

                    lines.append(line)


                info.set_text(
                    "STEP 5: FINAL PREDICTION\n\n"
                    f"K = {K}\n"
                    f"Actual Crop    : "
                    f"{encoder.classes_[actual_class]}\n"
                    f"Predicted Crop : "
                    f"{encoder.classes_[predicted_class]}"
                )


            return lines + [info]


        # ====================================================
        # CREATE ANIMATION
        # ====================================================

        distance_frames = min(
            30,
            len(sorted_indices)
        )

        total_frames = (
            distance_frames + 4
        )

        animation = FuncAnimation(
            fig,
            update,
            frames=total_frames,
            interval=350,
            repeat=True,
            blit=False
        )


        # ====================================================
        # DISPLAY
        # ====================================================

        plt.close(fig)

        display(
            HTML(
                animation.to_jshtml()
            )
        )


# ============================================================
# 11. CONNECT BUTTON
# ============================================================

run_button.on_click(
    run_knn
)


print("\nREADY!")
print("Select two features, select 'label' as target,")
print("choose K, and click Run KNN.")